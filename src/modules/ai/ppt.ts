/**
 * AI slide generation (.pptx via PptxGenJS). Owned by the AI services module.
 */

export interface PptOptions {
  onProgress?: ProgressReporter;
  slideCount?: number;
  language?: string;
  /** Open the generated file after writing it. */
  openAfter?: boolean;
}

export interface PptResult {
  filePath: string;
  /** Number of slides actually written to the file. */
  slideCount: number;
  title: string;
}

type PptxSlide = PptxGenJS.Slide;

const NOT_CONFIGURED = "请先在 PaperMiner 设置中配置 AI 服务";

const SLIDE_W = 10;
const SLIDE_H = 5.625;
const MARGIN_X = 0.6;
const CONTENT_W = SLIDE_W - MARGIN_X * 2;

const COLORS = {
  red: "A51D28",
  redDark: "7F1620",
  dark: "1F1F1F",
  body: "333333",
  muted: "6B6B6B",
  line: "E3E3E3",
  white: "FFFFFF",
  softRed: "F7E9EA",
};

/** CJK-capable sans-serif font for the current platform. */
function pickFontFace(): string {
  try {
    if (Zotero.isMac) return "PingFang SC";
    if (Zotero.isWin) return "Microsoft YaHei";
  } catch {
    // Zotero not available (tests) — fall through.
  }
  return "Arial";
}

function resolvePaperItem(
  item: Zotero.Item | null | undefined,
): Zotero.Item | null {
  if (!item) return null;
  if (item.isRegularItem()) return item;
  return getRegularItemForReader(item);
}

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

function timestampForFile(date: Date): string {
  const pad = (value: number) => String(value).padStart(2, "0");
  return [
    date.getFullYear(),
    pad(date.getMonth() + 1),
    pad(date.getDate()),
    "-",
    pad(date.getHours()),
    pad(date.getMinutes()),
    pad(date.getSeconds()),
  ].join("");
}

/** Output token budget: enough for the requested number of slides. */
function outlineTokenBudget(slideCount: number): number {
  const configured = getNumberPref("llmMaxTokens", 4096, 256, 65536, true);
  const needed = 1024 + slideCount * 260;
  return Math.min(8192, Math.max(configured, needed));
}

function addTopBar(slide: PptxSlide, pptx: PptxGenJS): void {
  slide.addShape(pptx.ShapeType.rect, {
    x: 0,
    y: 0,
    w: SLIDE_W,
    h: 0.09,
    fill: { color: COLORS.red },
    line: { color: COLORS.red },
  });
}

function renderCover(
  pptx: PptxGenJS,
  outline: PptOutline,
  meta: PaperMeta,
  language: string,
  font: string,
): void {
  const zh = language === "zh";
  const slide = pptx.addSlide();
  slide.background = { color: COLORS.red };
  slide.addText("PaperMiner · AI READING SLIDES", {
    x: 0.7,
    y: 0.5,
    w: 8.6,
    h: 0.3,
    fontSize: 11,
    color: "F2C9CD",
    fontFace: font,
    charSpacing: 1,
  });
  slide.addText(truncateDisplay(outline.title, 120), {
    x: 0.7,
    y: 1.3,
    w: 8.6,
    h: 1.9,
    fontSize: 30,
    bold: true,
    color: COLORS.white,
    fontFace: font,
    valign: "top",
    lineSpacingMultiple: 1.05,
    fit: "shrink",
  });
  slide.addText(truncateDisplay(outline.subtitle, 70), {
    x: 0.7,
    y: 3.25,
    w: 8.6,
    h: 0.5,
    fontSize: 16,
    color: "F6E7E8",
    fontFace: font,
  });
  if (meta.authors) {
    slide.addText(truncateDisplay(meta.authors, 100), {
      x: 0.7,
      y: 3.8,
      w: 8.6,
      h: 0.6,
      fontSize: 12,
      color: "F2C9CD",
      fontFace: font,
      lineSpacingMultiple: 1.1,
    });
  }
  slide.addText(
    zh ? "由 AI 基于论文全文生成" : "Generated by AI from the paper",
    {
      x: 0.7,
      y: 4.95,
      w: 8.6,
      h: 0.3,
      fontSize: 10,
      color: "F2C9CD",
      fontFace: font,
    },
  );
}

function renderAgenda(
  pptx: PptxGenJS,
  slides: PptSlideOutline[],
  language: string,
  font: string,
): void {
  const zh = language === "zh";
  const slide = pptx.addSlide();
  slide.background = { color: COLORS.white };
  addTopBar(slide, pptx);
  slide.addText(zh ? "目录" : "Contents", {
    x: MARGIN_X,
    y: 0.4,
    w: CONTENT_W,
    h: 0.7,
    fontSize: 26,
    bold: true,
    color: COLORS.red,
    fontFace: font,
    valign: "middle",
  });

  const total = slides.length;
  const twoColumns = total > 8;
  const perColumn = twoColumns ? Math.ceil(total / 2) : total;
  const fontSize = twoColumns ? (total > 16 ? 13 : 14) : 16;
  const rowHeight = twoColumns ? (total > 16 ? 0.24 : 0.28) : 0.34;
  // Keep each title within its column width so rows never wrap and overlap.
  const titleWidth = twoColumns ? 38 : 108;
  const itemWidth = twoColumns ? 4.0 : 8.4;

  slides.forEach((slideData, index) => {
    const secondColumn = twoColumns && index >= perColumn;
    const row = secondColumn ? index - perColumn : index;
    const x = secondColumn ? 5.2 : 0.8;
    const y = 1.35 + row * rowHeight;
    slide.addText(
      [
        {
          text: `${String(index + 1).padStart(2, "0")}  `,
          options: { color: COLORS.red, bold: true },
        },
        {
          text: truncateDisplay(slideData.title, titleWidth),
          options: { color: COLORS.body },
        },
      ],
      {
        x,
        y,
        w: itemWidth,
        h: rowHeight,
        fontSize,
        fontFace: font,
        valign: "middle",
        fit: "shrink",
      },
    );
  });
}

function bulletFontSize(bullets: string[]): number {
  const width = bullets.reduce((sum, bullet) => sum + displayWidth(bullet), 0);
  if (bullets.length >= 6 || width > 430) return 14;
  if (bullets.length >= 5 || width > 340) return 15;
  if (bullets.length >= 4 || width > 250) return 16;
  return 18;
}

function renderContentSlide(
  pptx: PptxGenJS,
  data: PptSlideOutline,
  pageNumber: number,
  totalPages: number,
  meta: PaperMeta,
  language: string,
  font: string,
): void {
  const zh = language === "zh";
  const slide = pptx.addSlide();
  slide.background = { color: COLORS.white };
  addTopBar(slide, pptx);
  const title = truncateDisplay(data.title, 64);
  // 24pt CJK characters are ~0.33in wide; shrink long titles so they do not
  // wrap into the divider line.
  const titleWidth = displayWidth(title);
  const titleFontSize = titleWidth > 52 ? 20 : titleWidth > 44 ? 22 : 24;
  slide.addText(title, {
    x: MARGIN_X,
    y: 0.32,
    w: CONTENT_W,
    h: 0.66,
    fontSize: titleFontSize,
    bold: true,
    color: COLORS.red,
    fontFace: font,
    valign: "middle",
    fit: "shrink",
  });
  slide.addShape(pptx.ShapeType.rect, {
    x: MARGIN_X,
    y: 1.08,
    w: CONTENT_W,
    h: 0.015,
    fill: { color: COLORS.line },
    line: { color: COLORS.line },
  });

  const bullets = data.bullets.slice(0, 6);
  if (bullets.length) {
    slide.addText(
      bullets.map((bullet, index) => ({
        text: bullet,
        options: {
          bullet: { characterCode: "25AA", indent: 16 },
          breakLine: index < bullets.length - 1,
          paraSpaceAfter: 10,
        },
      })),
      {
        x: MARGIN_X + 0.1,
        y: 1.3,
        w: CONTENT_W - 0.15,
        h: 3.55,
        fontSize: bulletFontSize(bullets),
        color: COLORS.body,
        fontFace: font,
        valign: "top",
        lineSpacingMultiple: 1.15,
        fit: "shrink",
      },
    );
  } else {
    slide.addText(zh ? "（本页无文字要点）" : "(no bullet points)", {
      x: MARGIN_X + 0.1,
      y: 1.4,
      w: CONTENT_W - 0.15,
      h: 0.6,
      fontSize: 16,
      italic: true,
      color: COLORS.muted,
      fontFace: font,
    });
  }

  const source = [meta.journal, meta.year].filter(Boolean).join(" · ");
  if (source) {
    slide.addText(`${zh ? "来源" : "Source"}：${truncateDisplay(source, 60)}`, {
      x: MARGIN_X,
      y: 5.15,
      w: 7.2,
      h: 0.28,
      fontSize: 9,
      color: COLORS.muted,
      fontFace: font,
      valign: "middle",
    });
  }
  slide.addText(`${pageNumber} / ${totalPages}`, {
    x: 8.6,
    y: 5.15,
    w: 0.8,
    h: 0.28,
    fontSize: 9,
    color: COLORS.muted,
    fontFace: font,
    align: "right",
    valign: "middle",
  });
}

function renderEndSlide(pptx: PptxGenJS, language: string, font: string): void {
  const zh = language === "zh";
  const slide = pptx.addSlide();
  slide.background = { color: COLORS.red };
  slide.addText(zh ? "谢谢观看" : "Thank You", {
    x: 0.7,
    y: 1.7,
    w: 8.6,
    h: 1.0,
    fontSize: 36,
    bold: true,
    color: COLORS.white,
    fontFace: font,
    align: "center",
    valign: "middle",
  });
  slide.addText(
    zh
      ? "本演示文稿由 PaperMiner 基于论文内容自动生成，可能存在偏差，请以论文原文为准。"
      : "This deck was generated by PaperMiner from the paper content. It may contain inaccuracies; refer to the paper for the authoritative version.",
    {
      x: 0.9,
      y: 3.0,
      w: 8.2,
      h: 0.9,
      fontSize: 13,
      color: "F6E7E8",
      fontFace: font,
      align: "center",
      lineSpacingMultiple: 1.2,
    },
  );
  slide.addText("PaperMiner", {
    x: 0.7,
    y: 5.0,
    w: 8.6,
    h: 0.3,
    fontSize: 10,
    color: "F2C9CD",
    fontFace: font,
    align: "center",
  });
}

function toUint8Array(
  result: string | ArrayBuffer | Blob | Uint8Array,
): Uint8Array {
  if (result instanceof Uint8Array) return result;
  if (result instanceof ArrayBuffer) return new Uint8Array(result);
  throw new Error("PPT 输出格式不受支持");
}

async function writePptxFile(pptx: PptxGenJS, title: string): Promise<string> {
  let output: string | ArrayBuffer | Blob | Uint8Array;
  try {
    output = await pptx.write({ outputType: "uint8array" });
  } catch (error) {
    throw new Error(`生成 PPT 文件内容失败：${errorToString(error)}`);
  }
  const bytes = toUint8Array(output);

  const customDir = String(getPref("pptOutputDir") || "").trim();
  const candidates: string[] = [];
  candidates.push(customDir || joinPath(getDownloadsDir(), "PaperMiner"));
  const fallbackDir = joinPath(getPluginDataDir(), "PaperMiner");
  if (!candidates.includes(fallbackDir)) candidates.push(fallbackDir);

  const filename = `${sanitizeFilename(title || "PaperMiner", 80)}-${timestampForFile(
    new Date(),
  )}.pptx`;

  let lastError: unknown = null;
  for (const dir of candidates) {
    try {
      await ensureDir(dir);
      const filePath = joinPath(dir, filename);
      await writeBinaryFile(filePath, bytes);
      return filePath;
    } catch (error) {
      lastError = error;
      log("writePptxFile failed for", dir, errorToString(error));
    }
  }
  throw new Error(`写入 PPT 文件失败：${errorToString(lastError)}`);
}

/**
 * Generate a 16:9 .pptx deck for a paper. Requires a configured AI service;
 * when the outline cannot be parsed a metadata-based fallback is used.
 */
export async function generatePpt(
  item: Zotero.Item,
  options: PptOptions = {},
): Promise<PptResult> {
  const regular = resolvePaperItem(item);
  if (!regular) throw new Error("请选择一个论文条目后再生成 PPT");
  if (!isPaperItem(regular)) {
    throw new Error("当前条目不是论文类型，无法生成 PPT");
  }
  if (!isLLMConfigured("ppt")) {
    throw new LLMError("config", NOT_CONFIGURED);
  }

  const report = (message: string, progress?: number) => {
    try {
      options.onProgress?.(message, progress);
    } catch {
      // ignore broken callbacks
    }
  };

  const requested = clamp(
    options.slideCount ?? getNumberPref("pptSlides", 12, 5, 30, true),
    5,
    30,
  );
  // Cover + agenda + closing slide take three pages.
  const contentCount = Math.max(2, requested - 3);

  report(t("ppt-extracting", "正在提取论文正文…"), 5);
  const extracted = await getPaperText(regular);
  if (extracted.source === "abstract") {
    report(t("ppt-abstract-only", "未找到 PDF 全文，将基于摘要生成"), 10);
  }
  const meta = getItemMeta(regular);
  const language = resolveOutputLanguage(
    options.language || String(getPref("pptLanguage") || "auto"),
    `${meta.title}\n${meta.abstract}\n${extracted.text.slice(0, 3000)}`,
  );

  report(t("ppt-outline", "正在生成 PPT 大纲…"), 15);
  let outline: PptOutline;
  try {
    const raw = await chatCompletion(
      buildPptOutlineMessages({
        meta,
        text: extracted.text,
        slideCount: contentCount,
        language,
        customPrompt: String(getPref("pptPrompt") || ""),
      }),
      {
        purpose: "ppt",
        stream: false,
        maxTokens: outlineTokenBudget(contentCount),
      },
    );
    outline = parsePptOutline(raw, {
      meta,
      slideCount: contentCount,
      language,
    });
  } catch (error) {
    if (
      error instanceof LLMError &&
      ["config", "auth", "rate", "abort"].includes(error.kind)
    ) {
      throw error;
    }
    log("PPT outline via LLM failed, using fallback:", errorToString(error));
    report(t("ppt-fallback", "大纲生成失败，已使用备用大纲"), 28);
    outline = buildFallbackOutline(meta, contentCount, language);
  }
  if (!outline.slides.length) {
    outline = buildFallbackOutline(meta, contentCount, language);
  }

  const pptx = new PptxGenJS();
  pptx.layout = "LAYOUT_16x9";
  pptx.author = "PaperMiner";
  pptx.company = "PaperMiner";
  pptx.subject = meta.title || "Paper";
  pptx.title = outline.title || meta.title || "PaperMiner";
  const font = pickFontFace();
  pptx.theme = { headFontFace: font, bodyFontFace: font };

  const totalPages = outline.slides.length + 3;
  renderCover(pptx, outline, meta, language, font);
  renderAgenda(pptx, outline.slides, language, font);

  report(t("ppt-rendering", "正在渲染幻灯片…"), 35);
  outline.slides.forEach((slideData, index) => {
    renderContentSlide(
      pptx,
      slideData,
      index + 3,
      totalPages,
      meta,
      language,
      font,
    );
    report(
      t("ppt-rendering", "正在渲染幻灯片…"),
      35 + Math.round(((index + 1) / outline.slides.length) * 50),
    );
  });
  renderEndSlide(pptx, language, font);

  report(t("ppt-writing", "正在写入文件…"), 90);
  const filePath = await writePptxFile(pptx, outline.title || meta.title);
  const openAfter = options.openAfter ?? Boolean(getPref("pptOpenAfter"));
  if (openAfter) {
    launchFile(filePath);
  }
  report(t("ppt-done", "PPT 已生成"), 100);
  return {
    filePath,
    slideCount: totalPages,
    title: outline.title || meta.title || "PaperMiner",
  };
}
