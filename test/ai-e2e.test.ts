const FIXTURE =
  "/Users/hao/Documents/dsh/paperminer/test/fixtures/sample-paper.pdf";
const OUTPUT_DIR = "/Users/hao/Documents/dsh/paperminer/.scaffold/test-out";

function jsonResponse(content: string): Response {
  return new Response(
    JSON.stringify({
      choices: [{ message: { role: "assistant", content } }],
    }),
    { status: 200, headers: { "content-type": "application/json" } },
  );
}

function sseResponse(text: string): Response {
  const encoder = new TextEncoder();
  const stream = new ReadableStream<Uint8Array>({
    start(controller) {
      controller.enqueue(
        encoder.encode(
          `data: ${JSON.stringify({
            choices: [{ delta: { content: text } }],
          })}\n\n`,
        ),
      );
      controller.enqueue(encoder.encode("data: [DONE]\n\n"));
      controller.close();
    },
  });
  return new Response(stream, {
    status: 200,
    headers: { "content-type": "text/event-stream" },
  });
}

const backup: Record<string, unknown> = {};
function remember(key: string): void {
  backup[key] = getPref(key as any);
  void key;
}

async function createPaper(): Promise<Zotero.Item> {
  const item = new Zotero.Item("journalArticle");
  item.libraryID = Zotero.Libraries.userLibraryID;
  item.setField("title", "PaperMiner E2E Paper");
  item.setField("publicationTitle", "Nature");
  item.setField("date", "2024-01-01");
  item.setField("abstractNote", "Testing AI features.");
  await item.saveTx();
  await Zotero.Attachments.importFromFile({
    file: FIXTURE,
    parentItemID: item.id,
    title: "Full Text PDF",
  });
  return item;
}

describe("PaperMiner AI end-to-end (mocked provider)", function () {
  this.timeout(120000);
  let item: Zotero.Item;
  const originalFetch = (globalThis as any).fetch;
  const originalPrefs: Record<string, unknown> = {};

  before(async function () {
    for (const key of [
      "llmPreset",
      "llmBaseURL",
      "llmApiKey",
      "llmModel",
      "llmStream",
      "summaryTag",
      "summaryLanguage",
      "summaryPrompt",
      "pptOutputDir",
      "pptSlides",
      "pptLanguage",
      "pptOpenAfter",
      "translateEngine",
      "translateTarget",
    ]) {
      originalPrefs[key] = getPref(key as any);
    }
    setPref("llmPreset", "openai" as never);
    setPref("llmBaseURL", "https://mock.local/v1" as never);
    setPref("llmApiKey", "test-key" as never);
    setPref("llmModel", "mock-model" as never);
    setPref("llmStream", true as never);
    setPref("summaryTag", "PaperMiner-Test" as never);
    setPref("summaryLanguage", "zh" as never);
    setPref("summaryPrompt", "" as never);
    setPref("pptOutputDir", OUTPUT_DIR as never);
    setPref("pptSlides", 6 as never);
    setPref("pptLanguage", "zh" as never);
    setPref("pptOpenAfter", false as never);
    setPref("translateEngine", "llm" as never);
    setPref("translateTarget", "zh-CN" as never);
    await Zotero.File.createDirectoryIfMissingAsync(OUTPUT_DIR);
    item = await createPaper();
  });

  after(async function () {
    (globalThis as any).fetch = originalFetch;
    for (const [key, value] of Object.entries(originalPrefs)) {
      setPref(key as any, value as never);
    }
    if (item) await item.eraseTx();
  });

  it("generates an AI summary note and reuses it", async function () {
    const calls: string[] = [];
    (globalThis as any).fetch = async (_url: string, init: any) => {
      const body = JSON.parse(init.body);
      calls.push(String(body.model));
      return jsonResponse(
        "## 一句话总结\n这是一段测试摘要。\n\n## 研究问题\n- 阅读助手是否有效？",
      );
    };
    const result = await generateSummary(item, { force: true });
    assert.isAbove(result.noteID, 0);
    assert.include(result.markdown, "测试摘要");
    const note = await findSummaryNote(item);
    assert.ok(note, "summary note should exist");
    assert.isTrue(note!.hasTag("PaperMiner-Test"));
    const html = note!.getNote();
    assert.include(html, "测试摘要");
    assert.isTrue(/<h2|<p/.test(html), "markdown should be rendered to HTML");
    assert.deepEqual(calls, ["mock-model"]);

    const again = await generateSummary(item);
    assert.isFalse(again.cached === false && again.noteID !== result.noteID);
  });

  it("generates a .pptx through the mocked outline", async function () {
    const outline = {
      title: "Test Slides",
      subtitle: "Generated by PaperMiner",
      slides: [
        { title: "Background", bullets: ["Point A", "Point B", "Point C"] },
        { title: "Method", bullets: ["Step 1", "Step 2"] },
        { title: "Results", bullets: ["Result 1", "Result 2"] },
        { title: "Limitations", bullets: ["Small sample"] },
      ],
    };
    (globalThis as any).fetch = async () =>
      jsonResponse(JSON.stringify(outline));
    let result: any;
    try {
      result = await generatePpt(item, { slideCount: 6 });
    } catch (error) {
      assert.fail(
        `generatePpt threw: ${(error as Error)?.stack || String(error)}`,
      );
    }
    assert.isObject(result, "generatePpt should return an object");
    assert.isNumber(
      result?.slideCount,
      `slideCount invalid: ${JSON.stringify(result)}`,
    );
    assert.isAbove(result.slideCount, 0);
    assert.isString(
      result?.filePath,
      `filePath invalid: ${JSON.stringify(result)}`,
    );
    assert.isTrue(result.filePath.startsWith(OUTPUT_DIR));
    const bytes = await (globalThis as any).IOUtils.read(result.filePath);
    assert.isAbove(bytes.length, 10000, "pptx file should not be tiny");
    const binary = new TextDecoder("latin1").decode(bytes);
    assert.include(binary, "ppt/slides/slide");
  });

  it("streams an LLM translation", async function () {
    (globalThis as any).fetch = async () => sseResponse("这是译文。");
    const chunks: string[] = [];
    const result = await translateText("This is a test sentence.", {
      onDelta: (delta) => chunks.push(delta),
      context: "A paper about AI reading assistants.",
    });
    assert.equal(result, "这是译文。");
    assert.equal(chunks.join(""), "这是译文。");
  });

  it("reports a friendly error when AI is not configured", async function () {
    setPref("llmApiKey", "" as never);
    let message = "";
    try {
      await generateSummary(item, { force: true });
    } catch (error) {
      message = (error as Error).message;
    }
    assert.include(message, "设置");
    setPref("llmApiKey", "test-key" as never);
  });
});
